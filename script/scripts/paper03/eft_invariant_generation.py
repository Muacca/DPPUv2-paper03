"""
Invariant-generation check for the final Landau-EFT basis (App G.5).

Scope:
    - Use the final full-shear basis T_A (App D.9).
    - Expand I2, I3, I4, W2 explicitly in (q_A, omega_i).
    - Check the component-level identity for I3.
    - Confirm that the low-order scalar terms used in the final Landau-EFT
      are generated by this invariant basis.

Author: Muacca
Date: 2026-03-15
"""

from __future__ import annotations

import io
import sys
import time

import sympy as sp


def _configure_utf8_stdio() -> None:
    for name in ("stdout", "stderr"):
        stream = getattr(sys, name)
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
            continue
        except Exception:
            pass

        buffer = getattr(stream, "buffer", None)
        if buffer is not None:
            setattr(sys, name, io.TextIOWrapper(buffer, encoding="utf-8", errors="replace"))


def build_spin2_basis() -> dict[int, sp.Matrix]:
    sqrt2 = sp.sqrt(2)
    sqrt6 = sp.sqrt(6)
    return {
        1: sp.diag(1, 1, -2) / sqrt6,
        2: sp.diag(1, -1, 0) / sqrt2,
        3: sp.Matrix([[0, 1, 0], [1, 0, 0], [0, 0, 0]]) / sqrt2,
        4: sp.Matrix([[0, 0, 1], [0, 0, 0], [1, 0, 0]]) / sqrt2,
        5: sp.Matrix([[0, 0, 0], [0, 0, 1], [0, 1, 0]]) / sqrt2,
    }


def main() -> None:
    _configure_utf8_stdio()

    start = time.perf_counter()
    q1, q2, q3, q4, q5 = sp.symbols("q1 q2 q3 q4 q5", real=True)
    w1, w2, w3 = sp.symbols("w1 w2 w3", real=True)

    T = build_spin2_basis()
    h = q1 * T[1] + q2 * T[2] + q3 * T[3] + q4 * T[4] + q5 * T[5]
    omega = sp.Matrix([w1, w2, w3])

    trace_h = sp.expand(sp.trace(h))
    I2 = sp.expand(sp.trace(h * h))
    I3 = sp.expand((omega.T * h * omega)[0])
    I4 = sp.expand(sp.trace(h * h * h))
    W2 = sp.expand((omega.T * omega)[0])

    hand_I3 = sp.expand(
        q1 * (w1**2 + w2**2 - 2 * w3**2) / sp.sqrt(6)
        + q2 * (w1**2 - w2**2) / sp.sqrt(2)
        + sp.sqrt(2) * q3 * w1 * w2
        + sp.sqrt(2) * q4 * w1 * w3
        + sp.sqrt(2) * q5 * w2 * w3
    )

    ortho_ok = True
    for a in range(1, 6):
        for b in range(1, 6):
            expected = 1 if a == b else 0
            if sp.simplify(sp.trace(T[a] * T[b]) - expected) != 0:
                ortho_ok = False

    residual_trace = sp.simplify(trace_h)
    residual_I2 = sp.simplify(I2 - (q1**2 + q2**2 + q3**2 + q4**2 + q5**2))
    residual_I3 = sp.simplify(I3 - hand_I3)

    assert ortho_ok
    assert residual_trace == 0
    assert residual_I2 == 0
    assert residual_I3 == 0

    elapsed = time.perf_counter() - start

    print("=" * 72)
    print("Invariant generation in the final Landau-EFT basis (App G.5)")
    print("=" * 72)
    print()
    print("[1] Final full-shear basis")
    print(f"  Tr(T_A T_B) = delta_AB: {'OK' if ortho_ok else 'FAIL'}")
    print(f"  tr(h) = {sp.sstr(trace_h)}")
    print()
    print("[2] Explicit invariant expansions")
    print(f"  I2 = tr(h^2) = {sp.sstr(I2)}")
    print(f"  W2 = omega_i omega_i = {sp.sstr(W2)}")
    print(f"  I3 = h_ij omega_i omega_j = {sp.sstr(I3)}")
    print(f"  I4 = tr(h^3) = {sp.sstr(I4)}")
    print()
    print("[3] Assertions")
    print(f"  I2 - sum_A q_A^2 = {sp.sstr(residual_I2)}")
    print(f"  I3 - hand-written q_A omega_i omega_j expression = {sp.sstr(residual_I3)}")
    print("  Result: all assertions passed")
    print()
    print(f"\nComputation time: {elapsed:.1f}s")
    print()
    print("*Script: scripts/paper03/eft_invariant_generation.py")


if __name__ == "__main__":
    main()
